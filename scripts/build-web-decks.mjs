#!/usr/bin/env node
// Generates the web landing page's deck manifest from content/decks/*.json so
// names, counts, locked state, and samples cannot drift from the app.

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const decksDir = path.join(root, 'content', 'decks');
const outputPath = path.join(root, 'web', 'src', 'data', 'decks.ts');
const checkOnly = process.argv.includes('--check');

const TONE_STYLES = {
  love: { fill: '#D85A30', ink: '#fff' },
  deep: { fill: '#2B4BD8', ink: '#fff' },
  silly: { fill: '#F5B400', ink: '#2B1A0F' },
  dreams: { fill: '#1E7A3C', ink: '#fff' },
  family: { fill: '#639922', ink: '#fff' },
  friends: { fill: '#D4537E', ink: '#fff' },
  late: { fill: '#7C5CFF', ink: '#FFF9E8' },
  distance: { fill: '#22C3D6', ink: '#08343C' },
  spicy: { fill: '#FF7A3D', ink: '#2B1A0F' },
  abusua: { fill: '#B06A1F', ink: '#FFF9E8' },
};

const decks = readdirSync(decksDir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => {
    const source = JSON.parse(readFileSync(path.join(decksDir, file), 'utf8'));
    const questions = Array.isArray(source.questions) ? source.questions : [];
    const tone = TONE_STYLES[source.tone];
    if (!tone) throw new Error(`${file}: no marketing colour for tone "${source.tone}"`);
    if (!source.slug || !source.title) throw new Error(`${file}: slug and title are required`);
    if (!questions.length) throw new Error(`${file}: no questions`);

    return {
      slug: source.slug,
      name: source.title,
      tagline: source.tagline ?? '',
      relationship: source.relationship_type,
      tone: source.tone,
      icon: source.icon,
      art: source.art_key,
      count: questions.length,
      locked: source.is_locked === true,
      fill: tone.fill,
      ink: tone.ink,
      samples: questions.slice(0, 3).map((question) => question.text),
      sort: Number(source.sort_order ?? 0),
    };
  })
  .sort((a, b) => a.sort - b.sort);

const manifest = decks.map(({ sort, ...deck }) => deck);
const stats = {
  total: manifest.length,
  free: manifest.filter((deck) => !deck.locked).length,
  locked: manifest.filter((deck) => deck.locked).length,
  questions: manifest.reduce((sum, deck) => sum + deck.count, 0),
};

const output = `// Generated by scripts/build-web-decks.mjs. Do not edit by hand.
// Run \`npm run build:web-decks\` after changing content/decks/*.json.

export type MarketingDeck = {
  slug: string;
  name: string;
  tagline: string;
  relationship: 'partner' | 'family' | 'friend';
  tone: string;
  icon: string;
  art: string;
  count: number;
  locked: boolean;
  fill: string;
  ink: string;
  samples: string[];
};

export const DECKS: MarketingDeck[] = ${JSON.stringify(manifest, null, 2)};

export const FREE_DECKS = DECKS.filter((deck) => !deck.locked);

export const LOCKED_DECKS = DECKS.filter((deck) => deck.locked);

export const DECK_STATS = ${JSON.stringify(stats, null, 2)} as const;
`;

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    console.error('web deck manifest is stale. Run: node scripts/build-web-decks.mjs');
    process.exit(1);
  }
  console.log('web deck manifest is up to date');
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output);
  console.log(
    `Wrote web/src/data/decks.ts (${stats.total} decks, ${stats.free} free, ${stats.locked} locked, ${stats.questions} questions)`,
  );
}
